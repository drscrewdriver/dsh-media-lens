/**
 * sync-hosts.mjs —— 从 hosts.mjs（唯一事实源）下发全部宿主声明写点。
 *
 * 以 dsh-perm-gate/scripts/sync-hosts.mjs 为底，按本仓改编：
 * 1. peer 为**必需**（无 peerDependenciesMeta.optional）：本插件无独立 CLI，
 *    只在宿主 profile 内装载。三项宿主子包 peer 全枚举写入；
 *    `@deepseek-ai/cordis` 保持必需 `^4.0.2` 不动。
 * 2. 写点载体：package.json `engines.dsh` + `peerDependencies`。本仓为纯服务端
 *    cordis 插件，**无 dsh.plugin.json**，故不写 manifest。
 * 3. README 托管块：本仓语言集仅 README.md（英文）。
 *
 * 双模式：默认只校验（exit 1 = 有漂移）；`--write` 实际写盘。
 * 用法：node scripts/sync-hosts.mjs [--write]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import assert from 'node:assert/strict'
import { supportedHosts, peerRange, developmentHost, hostPeerPackages, clientHostPeers } from './hosts.mjs'

const ROOT = new URL('..', import.meta.url)
const write = process.argv.includes('--write')
const read = (rel) => readFile(new URL(rel, ROOT), 'utf8')

// ── 0. hosts.mjs 自检 ────────────────────────────────────────────────────────
const RC_RE = /^\d+\.\d+\.\d+-rc\.\d+$/
assert(supportedHosts.length > 0, 'supportedHosts 不得为空')
assert.equal(new Set(supportedHosts).size, supportedHosts.length, 'supportedHosts 有重复项')
for (const v of supportedHosts) assert(RC_RE.test(v), `非 rc 版本混入枚举: ${v}（本插件只收 rc）`)
assert(supportedHosts.includes(developmentHost), 'developmentHost 必须在 supportedHosts 内')

// ── 1. package.json：engines.dsh + peerDependencies（宿主子包，全枚举，必需） ──
const pkgUrl = new URL('package.json', ROOT)
const pkgOriginal = await read('package.json')
const pkg = JSON.parse(pkgOriginal)
pkg.engines ??= {}
pkg.engines.dsh = peerRange
pkg.peerDependencies ??= {}
for (const name of hostPeerPackages) {
  // 枚举串即白名单：运行时闸门把每个 dsh-* peer 对着宿主版本做全枚举匹配，
  // 枚举外宿主在挂载预检即拒（0.2.1-alpha.4 起 engines.dsh 优先裁决）。
  pkg.peerDependencies[name] = peerRange
}
// client 半身消费的宿主包：同串枚举，且必须保持 optional（宿主 profile 提供）。
for (const name of clientHostPeers) {
  pkg.peerDependencies[name] = peerRange
  pkg.peerDependenciesMeta ??= {}
  pkg.peerDependenciesMeta[name] = { optional: true }
}
// 本仓 peer 必需：服务端三件套不应带 optional 元数据（client 三件套的 optional 在上方强制）。
if (pkg.peerDependenciesMeta) {
  for (const name of hostPeerPackages) {
    assert(pkg.peerDependenciesMeta[name]?.optional !== true, `${name} 为必需 peer，不应带 peerDependenciesMeta.optional`)
  }
}
const pkgExpected = JSON.stringify(pkg, null, 2) + '\n'

// ── 1b. dsh.plugin.json：engines.dsh + version 镜像（以 package.json 为准） ──
const pluginJsonUrl = new URL('dsh.plugin.json', ROOT)
const pluginOriginal = await read('dsh.plugin.json')
const manifest = JSON.parse(pluginOriginal)
manifest.engines ??= {}
manifest.engines.dsh = peerRange
manifest.version = pkg.version
const manifestExpected = JSON.stringify(manifest, null, 2) + '\n'

// ── 2. README.md：托管块（支持清单 + 运行时已验证清单） ──────────────────────
const BEGIN = '<!-- host-compat:begin — generated by scripts/sync-hosts.mjs from scripts/hosts.mjs; DO NOT EDIT -->'
const END = '<!-- host-compat:end -->'
const versionList = supportedHosts.map((v) => `\`${v}\``).join(' ')
const lines = [
  `- **Supported DSH hosts:** ${versionList} (${supportedHosts.length} rc across lines 0.1.7 / 0.2.0 / 0.2.1)`,
]
// farm 保留场实测通过清单（.compat-results/verified.json，若存在）
const verifiedUrl = new URL('.compat-results/verified.json', ROOT)
if (existsSync(verifiedUrl)) {
  const { verified = [] } = JSON.parse(await readFile(verifiedUrl, 'utf8'))
  if (verified.length > 0) {
    lines.push(`- **Runtime-verified:** ${verified.map((v) => `\`${v}\``).join(', ')} — evidence in \`.compat-results/\``)
  }
}
const block = `${BEGIN}\n${lines.join('\n')}\n${END}`
const readmeUrl = new URL('README.md', ROOT)
const readmeOriginal = await read('README.md')
const beginAt = readmeOriginal.indexOf(BEGIN)
let readmeExpected
if (beginAt === -1) {
  const at = readmeOriginal.search(/^## /m)
  assert(at !== -1, 'README.md 找不到插入锚点（第一个二级标题）')
  readmeExpected = readmeOriginal.slice(0, at) + block + '\n\n' + readmeOriginal.slice(at)
} else {
  const endAt = readmeOriginal.indexOf(END, beginAt)
  assert(endAt !== -1, 'README.md 管理块缺少 end 标记')
  const current = readmeOriginal.slice(beginAt, endAt + END.length)
  readmeExpected = readmeOriginal.slice(0, beginAt) + block + readmeOriginal.slice(endAt + END.length)
}

// ── 3. 汇总校验/写盘 ────────────────────────────────────────────────────────
const drift = []
if (pkgOriginal !== pkgExpected) drift.push('package.json (engines.dsh / peerDependencies)')
if (pluginOriginal !== manifestExpected) drift.push('dsh.plugin.json (engines.dsh / version)')
if (readmeOriginal !== readmeExpected) drift.push('README.md (host-compat 管理块)')

if (write) {
  if (pkgOriginal !== pkgExpected) {
    await writeFile(pkgUrl, pkgExpected)
    console.log('write  package.json (engines.dsh + peerDependencies 全枚举)')
  } else console.log('ok     package.json')
  if (pluginOriginal !== manifestExpected) {
    await writeFile(pluginJsonUrl, manifestExpected)
    console.log('write  dsh.plugin.json (engines.dsh + version)')
  } else console.log('ok     dsh.plugin.json')
  if (readmeOriginal !== readmeExpected) {
    await writeFile(readmeUrl, readmeExpected)
    console.log('write  README.md (host-compat 管理块)')
  } else console.log('ok     README.md')
  console.log('done   --write 完成')
} else if (drift.length === 0) {
  console.log('ok     全部写点与 hosts.mjs 一致')
} else {
  for (const p of drift) console.error(`drift  ${p}`)
  console.error('\n运行 node scripts/sync-hosts.mjs --write 修复')
  process.exit(1)
}
